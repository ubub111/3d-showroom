import { expect, test } from '@playwright/test'

test('категории и слайдер работают на узком и широком экране', async ({ page }) => {
  test.setTimeout(70_000)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '3D-шоурум' })).toBeVisible()
  const carousel = page.getByRole('group', { name: 'Слайдер категорий' })
  await expect(carousel.locator('.is-active h2')).toHaveText('Жетоны')
  const next = page.getByRole('button', { name: 'Следующий слайд' })
  await next.click()
  await expect(carousel.locator('.is-active h2')).toHaveText('Значки')
  await next.press('ArrowLeft')
  await expect(carousel.locator('.is-active h2')).toHaveText('Жетоны')
  await page.getByRole('button', { name: 'Список' }).click()
  await expect(page.locator('.vertical-item')).toHaveCount(4)
  await page.locator('.vertical-item').getByRole('link', { name: /Награды/ }).click()
  await expect(page.getByRole('heading', { name: 'Награды', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Карусель' }).click()
  await page.getByRole('link', { name: /Медали/ }).click()
  await page.getByRole('link', { name: /Медаль «Север»/ }).click()
  await expect(page.locator('canvas')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Медаль «Север»' })).toBeVisible()
  await page.getByRole('link', { name: 'Вернуться в каталог' }).click()
  await expect(page.getByRole('heading', { name: 'Медали', exact: true })).toBeVisible({ timeout: 15_000 })
  expect(await page.locator('body').evaluate((body) => body.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
})

test('модель, смена отделки и сохранение комплектации', async ({ page, browser, isMobile }) => {
  test.setTimeout(75_000)
  await page.goto('/#/catalog/awards')
  await page.getByRole('link', { name: /Награда «Грань»/ }).click()
  await expect(page.getByRole('button', { name: 'Вращать автоматически' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Вращать автоматически' }).click()
  const canvas = page.locator('canvas')
  await expect(canvas).toBeVisible()
  await expect(canvas).toHaveAttribute('aria-label', /Награда «Грань»/)
  if (!isMobile) {
    const area = (await canvas.boundingBox())!
    const start = { x: area.x + area.width / 2, y: area.y + area.height / 2 }
    const original = await canvas.screenshot()
    await page.mouse.move(start.x, start.y)
    await page.mouse.down()
    await page.mouse.move(start.x + 120, start.y + 24, { steps: 8 })
    await page.mouse.up()
    await expect.poll(async () => (await canvas.screenshot()).equals(original)).toBe(false)
    await page.getByRole('button', { name: 'Сбросить ракурс' }).click()
  }
  const frame = await canvas.screenshot()
  await page.getByText('Графит', { exact: true }).click()
  await expect(page.getByRole('radio', { name: 'Графит' })).toBeChecked()
  await expect.poll(async () => (await canvas.screenshot()).equals(frame)).toBe(false)

  const tallResponse = page.waitForResponse((response) => response.url().endsWith('/models/facet-tall.glb'))
  await page.getByText('Высокая', { exact: true }).click()
  expect((await tallResponse).ok()).toBeTruthy()
  await expect(page.locator('.price')).toHaveText(/6\s*100/)
  const tallFrame = await canvas.screenshot()
  await page.getByRole('button', { name: 'Приблизить' }).click()
  await expect.poll(async () => (await canvas.screenshot()).equals(tallFrame)).toBe(false)
  await page.getByRole('button', { name: 'Сбросить ракурс' }).click()
  await page.getByRole('button', { name: 'Сохранить комплектацию' }).click()
  const link = await page.getByLabel('Ссылка на комплектацию').inputValue()
  expect(link).toContain('finish=smoke&base=tall')
  await page.reload()
  await expect(page.getByRole('radio', { name: 'Графит' })).toBeChecked()

  const context = await browser.newContext()
  try {
    const shared = await context.newPage()
    await shared.goto(link)
    await expect(shared.getByRole('radio', { name: 'Высокая' })).toBeChecked()
    await expect(shared.getByRole('radio', { name: 'Графит' })).toBeChecked()
  } finally {
    await context.close()
  }
})

test('подборка отличает комплектации, сохраняет тираж и даёт ссылки', async ({ page }) => {
  test.setTimeout(60_000)
  await page.goto('/#/product/facet')
  const add = page.getByRole('button', { name: 'В корзину', exact: true })
  await add.click()
  await add.click()
  await page.getByText('Графит', { exact: true }).click()
  await add.click()
  await page.getByRole('button', { name: 'Корзина, 2 позиций' }).click()
  await page.getByRole('dialog', { name: 'Корзина' }).getByRole('link', { name: 'Открыть подборку' }).click()

  const standard = page.getByRole('listitem').filter({ hasText: 'Янтарь' })
  const graphite = page.getByRole('listitem').filter({ hasText: 'Графит' })
  await expect(standard.getByRole('textbox')).toHaveValue('2')
  await expect(graphite.getByRole('textbox')).toHaveValue('1')
  await graphite.getByRole('textbox').fill('15')
  await graphite.getByRole('textbox').press('Enter')
  await expect(page.getByRole('complementary', { name: 'Итоги подборки' })).toContainText(/84\s*835/)
  await page.reload()
  await expect(graphite.getByRole('textbox')).toHaveValue('15')

  await page.getByRole('button', { name: 'Показать текст' }).click()
  const text = await page.getByRole('textbox', { name: 'Текст подборки' }).inputValue()
  expect(text).toContain('finish=smoke&base=standard')
  expect(text).toContain('× 15 шт.')
  await graphite.getByRole('link').click()
  await expect(page.getByRole('radio', { name: 'Графит' })).toBeChecked()
  await page.getByRole('link', { name: 'Вернуться к подборке' }).click()
  await graphite.getByRole('button', { name: /Убрать/ }).click()
  await expect(page.getByRole('listitem')).toHaveCount(1)
})

test('быстрый поиск, скидка и скачивание заявки', async ({ page }) => {
  test.setTimeout(65_000)
  await page.goto('/')
  await page.getByRole('button', { name: 'Поиск', exact: true }).click()
  await page.getByRole('searchbox').fill('AW-001')
  const result = page.getByRole('dialog', { name: 'Поиск по магазину' }).getByRole('link', { name: /Грань/ })
  await expect(result).toHaveCount(1)
  await result.click()
  await page.getByRole('button', { name: 'Фото изделия' }).click()
  await expect(page.getByRole('img', { name: 'Награда «Грань»' })).toBeVisible()
  await page.getByRole('button', { name: /от 10 шт/ }).click()
  await page.getByRole('button', { name: 'К оформлению' }).click()
  const cart = page.getByRole('dialog', { name: 'Корзина' })
  await expect(cart).toContainText('Скидка за тираж 5%')
  await expect(cart).toContainText(/46\s*550/)
  await cart.getByRole('button', { name: 'Оформить заказ' }).click()
  await cart.getByLabel('Имя', { exact: true }).fill('Тест')
  await cart.getByLabel('Телефон', { exact: true }).fill('+7 900 000-00-00')
  await cart.getByRole('radio', { name: 'Курьер', exact: true }).check()
  const file = page.waitForEvent('download')
  await cart.getByRole('button', { name: 'Скачать заявку' }).click()
  expect((await file).suggestedFilename()).toBe('forma-zayavka.txt')
  await expect(cart.getByRole('status')).toHaveText('Заявка скачана')
})
